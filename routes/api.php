        Route::get('/dashboard', AdminDashboardController::class);
        Route::post('/users', [UserController::class, 'store'])->middleware('throttle:10,1');
        Route::patch('/users/{user}', [UserController::class, 'update'])->middleware('throttle:30,1');
        Route::post('/currencies', [CurrencyController::class, 'store'])->middleware('throttle:10,1');
        Route::patch('/currencies/{currency}', [CurrencyController::class, 'update'])->middleware('throttle:30,1');
        Route::get('/rates', [ExchangeRateController::class, 'index']);
        Route::post('/rates', [ExchangeRateController::class, 'store'])->middleware('throttle:30,1');
