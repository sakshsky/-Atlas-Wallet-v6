        Route::post('/money-movements/{moneyMovement}/complete', [AdminMoneyMovementController::class, 'complete'])->middleware(['throttle:10,1', 'money.idempotent']);
        Route::get('/compliance-cases', [ComplianceCaseController::class, 'index']);
        Route::patch('/compliance-cases/{complianceCase}', [ComplianceCaseController::class, 'update'])->middleware('throttle:20,1');
        Route::get('/reconciliations', [ReconciliationController::class, 'index']);
        Route::post('/reconciliations', [ReconciliationController::class, 'store'])->middleware('throttle:3,10');
    });
});
