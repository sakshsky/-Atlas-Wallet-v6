        Route::post('/wallets/{wallet}/adjust', [WalletAdjustmentController::class, 'store'])->middleware(['throttle:20,1', 'money.idempotent']);
        Route::post('/transactions/{walletTransaction}/reverse', [ReversalController::class, 'store'])->middleware(['throttle:10,1', 'money.idempotent']);
        Route::get('/webhooks', [WebhookController::class, 'index']);
        Route::post('/webhooks', [WebhookController::class, 'store'])->middleware('throttle:10,1');
        Route::delete('/webhooks/{webhook}', [WebhookController::class, 'destroy'])->middleware('throttle:10,1');
