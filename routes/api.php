Route::post('/login', [AuthController::class, 'login'])->middleware(['guest', 'throttle:5,1']);
Route::get('/health', function () { try { DB::select('SELECT 1'); return response()->json(['status' => 'healthy', 'timestamp' => now()->toIso8601String(), 'version' => '1.1.0']); } catch (\Throwable) { return response()->json(['status' => 'unavailable', 'timestamp' => now()->toIso8601String()], 503); } })->middleware('throttle:30,1');
Route::post('/2fa/challenge', [TwoFactorController::class, 'challenge'])->middleware(['guest', 'throttle:5,1']);
Route::middleware('auth:sanctum')->group(function () {
    Route::post('/logout', [AuthController::class, 'logout']);
    Route::post('/email/verification/send', [EmailVerificationController::class, 'send'])->middleware('throttle:5,1');
    Route::get('/email/verify/{id}/{hash}', [EmailVerificationController::class, 'verify'])->middleware(['signed', 'throttle:6,1'])->name('verification.verify');
    Route::get('/dashboard', DashboardController::class);
    Route::post('/2fa/enable', [TwoFactorController::class, 'enable'])->middleware(['verified', 'throttle:3,10']);
    Route::post('/2fa/confirm', [TwoFactorController::class, 'confirm'])->middleware(['verified', 'throttle:5,1']);
    Route::delete('/2fa', [TwoFactorController::class, 'disable'])->middleware(['verified', '2fa', 'throttle:3,10']);
    Route::post('/wallets', [WalletController::class, 'store'])->middleware(['verified', '2fa']);
    Route::get('/wallets/{wallet}/transactions', [WalletController::class, 'transactions'])->middleware(['verified', '2fa']);
    Route::post('/transfers', [TransferController::class, 'store'])->middleware(['verified', '2fa', 'throttle:20,1', 'money.idempotent']);
    Route::post('/kyc', [KycController::class, 'store'])->middleware(['verified', '2fa', 'throttle:3,60']);
    Route::post('/trades/quote', [TradeController::class, 'quote'])->middleware(['verified', '2fa', 'throttle:60,1']);
    Route::post('/trades', [TradeController::class, 'store'])->middleware(['verified', '2fa', 'throttle:20,1', 'money.idempotent']);
    Route::get('/beneficiaries', [BeneficiaryController::class, 'index'])->middleware(['verified', '2fa']);
    Route::post('/beneficiaries', [BeneficiaryController::class, 'store'])->middleware(['verified', '2fa', 'throttle:10,1']);
    Route::delete('/beneficiaries/{beneficiary}', [BeneficiaryController::class, 'destroy'])->middleware(['verified', '2fa', 'throttle:10,1']);
    Route::get('/money-movements', [MoneyMovementController::class, 'index'])->middleware(['verified', '2fa']);
    Route::post('/deposits', [MoneyMovementController::class, 'deposit'])->middleware(['verified', '2fa', 'throttle:10,1', 'money.idempotent']);
    Route::post('/withdrawals', [MoneyMovementController::class, 'withdraw'])->middleware(['verified', '2fa', 'throttle:5,1', 'money.idempotent']);
    Route::get('/exports', [UserExportController::class, 'index'])->middleware(['verified', '2fa']);
    Route::post('/exports', [UserExportController::class, 'store'])->middleware(['verified', '2fa', 'throttle:2,60']);
    Route::get('/exports/{userExport}/download', [UserExportController::class, 'download'])->middleware(['verified', '2fa', 'throttle:10,1']);
